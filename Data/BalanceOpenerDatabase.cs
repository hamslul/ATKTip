    public static JobOpenerHints? GetHints(string specName) => BySpec.GetValueOrDefault(specName);

    private static HashSet<string> H(params string[] values)
        => new(values, StringComparer.OrdinalIgnoreCase);

    private static JobOpenerVariant V(string name, params OpenerStep[] steps)
        => new() { Name = name, Steps = steps };

    private static OpenerStep G(string abilityName)
        => new() { AbilityName = abilityName, Type = OpenerActionType.Gcd };

    private static OpenerStep O(string abilityName)
        => new() { AbilityName = abilityName, Type = OpenerActionType.Ogcd };
