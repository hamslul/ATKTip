namespace ATKTip.Data;

public static class BalanceOpenerDatabase
{
    public enum OpenerActionType
    {
        Gcd,
        Ogcd,
    }

    public sealed class OpenerStep
    {
        public string AbilityName { get; init; } = string.Empty;
        public OpenerActionType Type { get; init; }
        public bool IsGcd => Type == OpenerActionType.Gcd;
        public bool IsOgcd => Type == OpenerActionType.Ogcd;
    }

    public sealed class JobOpenerVariant
    {
        public string Name { get; init; } = string.Empty;
        public IReadOnlyList<OpenerStep> Steps { get; init; } = [];
        public IReadOnlyList<string> GcdSequence
            => Steps.Where(static step => step.IsGcd).Select(static step => step.AbilityName).ToArray();
        public IReadOnlyList<string> OgcdSequence
            => Steps.Where(static step => step.IsOgcd).Select(static step => step.AbilityName).ToArray();
    }

    public sealed class JobOpenerHints
    {
        public HashSet<string> BurstStarters { get; init; } = new(StringComparer.OrdinalIgnoreCase);
        public IReadOnlyList<JobOpenerVariant> Variants { get; init; } = [];
        public IReadOnlyList<IReadOnlyList<string>> OpenerVariants
            => Variants.Select(static variant => (IReadOnlyList<string>)variant.GcdSequence.ToArray()).ToArray();
    }

